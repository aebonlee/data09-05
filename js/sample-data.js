/*
 * 예시 데이터(가상) — 실제 회사 자료가 아닙니다.
 * 수강생 실제 파일을 받기 전, 화면과 계산을 시연하기 위해 만든 값입니다.
 * 품번·품명·고객사·단가·날짜는 모두 지어낸 것입니다.
 * 머리행 이름은 일부러 기획서 필드명과 조금 다르게 두어(자재코드·현재고 등)
 * 「컬럼 짝짓기」가 실제로 동작하는 모습을 보이게 했습니다.
 */
(function (root) {
  'use strict';
  var CUR = '2026-08-31';
  var PREV = '2026-07-31';

  // [자재코드, 자재명, 대분류, 전월 현재고, 당월 현재고, 단가, 최근 출고일(없으면 ''), 최근 입고일]
  var RAW = [
    ['RM-1001', '예시원료 A', '원료', 1200, 1500, 3200, '2026-08-28', '2026-08-20'],
    ['RM-1002', '예시원료 B', '원료', 800, 640, 4100, '2026-08-25', '2026-07-15'],
    ['RM-1003', '예시원료 C', '원료', 300, 900, 2750, '2026-08-05', '2026-08-26'],
    ['RM-1004', '예시원료 D', '원료', 150, 150, 5200, '2026-03-10', '2025-12-02'],
    ['RM-2001', '예시부자재 A', '부자재', 5000, 4200, 120, '2026-08-30', '2026-08-18'],
    ['RM-2002', '예시부자재 B', '부자재', 2400, 3100, 95, '2026-06-12', '2026-08-11'],
    ['RM-2003', '예시부자재 C', '부자재', 600, 600, 310, '2025-07-01', '2025-05-20'],
    ['RM-2004', '예시부자재 D', '부자재', 0, 1800, 150, '', '2026-08-22'],
    ['RM-3001', '예시포장재 A', '포장재', 9000, 7600, 45, '2026-08-29', '2026-08-01'],
    ['RM-3002', '예시포장재 B', '포장재', 1200, 0, 60, '2026-08-14', '2026-06-03'],
    ['RM-3003', '예시포장재 C', '포장재', 400, 950, 0, '', '2025-06-15'],
    ['RM-3004', '예시포장재 D', '포장재', 2000, 2600, 38, '2026-02-20', '2026-01-10']
  ];
  // RM-3003 단가 0 은 「단가표에 없음」을 뜻하도록 아래에서 빼 둡니다.

  // [제품코드, 제품명, 고객사, 전월, 당월, 단가, 최근 출고일, 최근 입고일]
  var PROD = [
    ['FG-501', '예시제품 가', '예시고객사 1', 400, 520, 18000, '2026-08-29', '2026-08-27'],
    ['FG-502', '예시제품 나', '예시고객사 1', 260, 180, 22000, '2026-08-21', '2026-08-02'],
    ['FG-503', '예시제품 다', '예시고객사 2', 90, 90, 35000, '2026-01-15', '2025-11-20'],
    ['FG-504', '예시제품 라', '예시고객사 2', 500, 740, 12500, '2026-07-02', '2026-08-19'],
    ['FG-505', '예시제품 마', '예시고객사 3', 0, 300, 15000, '', '2026-08-25'],
    ['FG-506', '예시제품 바', '예시고객사 3', 120, 0, 41000, '2026-08-10', '2026-05-12'],
    ['FG-507', '예시제품 사', '예시고객사 3', 75, 75, 27000, '2025-06-30', '2025-04-02']
  ];

  function stockTable(list, headers, col) {
    return [headers].concat(list.filter(function (r) { return r[col] !== 0; }).map(function (r) { return [r[0], r[1], r[2], r[col]]; }));
  }

  // 출고·입고 이력: 최근 날짜 1건 + 앞선 달 1건씩(수량은 가상)
  function history(lists, dateCol, qtyFactor) {
    var rows = [];
    lists.forEach(function (list) {
      list.forEach(function (r) {
        var d = r[dateCol];
        if (!d) return;
        rows.push([r[0], d, Math.max(1, Math.round((r[3] + r[4]) * qtyFactor))]);
        var y = +d.slice(0, 4), m = +d.slice(5, 7) - 1;
        if (m < 1) { m += 12; y -= 1; }
        rows.push([r[0], y + '-' + (m < 10 ? '0' : '') + m + '-10', Math.max(1, Math.round(r[3] * qtyFactor))]);
      });
    });
    rows.sort(function (a, b) { return a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : 0; });
    return rows;
  }

  function build() {
    var priceRows = [];
    RAW.concat(PROD).forEach(function (r) {
      if (r[0] === 'RM-3003') return; // 단가 미매칭 시연
      // 전월 단가(7월 1일 적용)와 당월 단가(8월 1일 적용)를 따로 둡니다 — 일부만 변동
      var before = r[0] === 'RM-1001' ? 3000 : r[0] === 'FG-504' ? 12000 : r[5];
      priceRows.push([r[0], before, '2026-07-01']);
      if (before !== r[5]) priceRows.push([r[0], r[5], '2026-08-01']);
    });
    return {
      rawCur: stockTable(RAW, ['자재코드', '자재명', '대분류', '현재고'], 4),
      rawPrev: stockTable(RAW, ['자재코드', '자재명', '대분류', '현재고'], 3),
      prodCur: stockTable(PROD, ['제품코드', '제품명', '고객사', '재고수량'], 4),
      prodPrev: stockTable(PROD, ['제품코드', '제품명', '고객사', '재고수량'], 3),
      inbound: [['품번', '입고일자', '입고수량']].concat(history([RAW, PROD], 7, 0.3)),
      outbound: [['품번', '출고일자', '출고수량']].concat(history([RAW, PROD], 6, 0.25)),
      price: [['품번', '단가', '적용일']].concat(priceRows)
    };
  }

  var FILE_NAMES = {
    rawCur: '예시데이터_원자재재고_당월.csv',
    rawPrev: '예시데이터_원자재재고_전월.csv',
    prodCur: '예시데이터_제품재고_당월.csv',
    prodPrev: '예시데이터_제품재고_전월.csv',
    inbound: '예시데이터_입고이력.csv',
    outbound: '예시데이터_출고이력.csv',
    price: '예시데이터_단가표.csv'
  };

  var api = { CUR: CUR, PREV: PREV, build: build, FILE_NAMES: FILE_NAMES };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.InvSample = api;
})(typeof window !== 'undefined' ? window : this);
